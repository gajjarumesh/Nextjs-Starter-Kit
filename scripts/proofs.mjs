// Regenerates src/config/proofs.ts from a real test run, so the sales page never states a
// number by hand. Needs Postgres (same as `npm test`). Usage: node scripts/proofs.mjs
import { execSync } from "node:child_process";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const strip = (s) => s.replace(/\x1b\[[0-9;]*m/g, "");
const run = (cmd) => {
  try {
    return strip(
      execSync(cmd, {
        encoding: "utf8",
        stdio: ["ignore", "pipe", "pipe"],
        env: { ...process.env, FORCE_COLOR: "0" },
      }),
    );
  } catch (err) {
    console.error(strip(String(err.stdout ?? "")) + strip(String(err.stderr ?? "")));
    throw new Error(`Failed: ${cmd}`);
  }
};

const all = run("npx vitest run --reporter=json");
const json = JSON.parse(all.slice(all.indexOf("{")));
if (json.numFailedTests > 0)
  throw new Error("Tests are failing; fix them before regenerating proofs.");
const files = json.testResults.length;
const total = json.numPassedTests;

const crossTenant = json.testResults
  .filter((f) => /cross-tenant-routes|tenant-isolation/.test(f.name))
  .flatMap((f) => [
    `✓ ${f.name.split("/tests/")[1]}`,
    ...f.assertionResults.map((a) => `  ✓ ${a.ancestorTitles.at(-1)} › ${a.title}`),
  ]);
const crossCount = json.testResults
  .filter((f) => /cross-tenant-routes|tenant-isolation/.test(f.name))
  .reduce((n, f) => n + f.assertionResults.length, 0);

const e2e = readdirSync("e2e").filter((f) => f.endsWith(".spec.ts"));
const e2eTests = e2e.reduce(
  (n, f) => n + (readFileSync(`e2e/${f}`, "utf8").match(/^test\(/gm) ?? []).length,
  0,
);

const types = readFileSync("src/server/billing/types.ts", "utf8");
const start = types.indexOf("export interface BillingProvider");
const iface = types
  .slice(start, types.indexOf("\n}", start) + 2)
  .split("\n")
  .filter((l) => !l.trim().startsWith("/**") && !l.trim().startsWith("*"))
  .join("\n");

const date = new Date().toISOString().slice(0, 10);
const out = `// Generated by scripts/proofs.mjs on ${date} from a real test run. Do not edit by hand.
export const PROOFS = {
  testSummary: ${JSON.stringify(`${crossCount} isolation tests pass in CI, part of ${total} unit and integration tests.`)},
  crossTenantOutput: ${JSON.stringify(`$ npx vitest run tests/integration/tenant-isolation.test.ts tests/integration/cross-tenant-routes.test.ts\n\n${crossTenant.join("\n")}\n\n Tests  ${crossCount} passed (${crossCount})`)},
  billingInterface: ${JSON.stringify(`// src/server/billing/types.ts\n${iface}`)},
  testCounts: ${JSON.stringify(`${total} unit and integration tests across ${files} files (real Postgres), plus ${e2eTests} Playwright journeys. Tests last regenerated ${date}.`)},
};
`;
writeFileSync("src/config/proofs.ts", out);
console.log(`proofs: ${total} tests, ${crossCount} isolation tests, ${e2eTests} e2e`);
